/**
 * Prepares the two static files the country map needs, from packages rather than by hand.
 *
 *   public/geo/countries-110m.json  the borders themselves (world-atlas, from Natural Earth)
 *   src/lib/country-codes.ts        numeric ISO 3166-1 id -> alpha-2, because the borders are keyed by the
 *                                   numeric code while every country we store is an alpha-2 one
 *
 * Both outputs are committed. They are static reference data that changes about as often as a border does, and
 * committing them keeps development and production identical with no build step in between.
 *
 * Run with: node scripts/generate-map-data.mjs
 */

import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import countries from "i18n-iso-countries";

const require = createRequire(import.meta.url);
const atlasPath = require.resolve("world-atlas/countries-110m.json");
const atlas = JSON.parse(readFileSync(atlasPath, "utf8"));

writeFileSync("public/geo/countries-110m.json", readFileSync(atlasPath));

const geometries = atlas.objects.countries.geometries;
const missing = [];
const entries = geometries
  .flatMap((geometry) => {
    const alpha2 = geometry.id ? countries.numericToAlpha2(geometry.id) : undefined;
    if (!alpha2) {
      // Territories without an ISO 3166-1 code. They draw as "no data", which is what they are to us.
      missing.push(geometry.properties?.name ?? geometry.id);
      return [];
    }
    return [[geometry.id, alpha2]];
  })
  .sort(([a], [b]) => a.localeCompare(b));

const lines = entries.map(([id, alpha2]) => `  "${id}": "${alpha2}",`).join("\n");
writeFileSync(
  "src/lib/country-codes.ts",
  `// Generated by scripts/generate-map-data.mjs — do not edit by hand.
// The country borders are keyed by the numeric ISO 3166-1 code; everything this product stores is alpha-2.

export const ALPHA2_BY_NUMERIC: Record<string, string> = {
${lines}
};

/** alpha-2 to the numeric id the map's geographies are keyed by. */
export const NUMERIC_BY_ALPHA2: Record<string, string> = Object.fromEntries(
  Object.entries(ALPHA2_BY_NUMERIC).map(([numeric, alpha2]) => [alpha2, numeric]),
);
`,
);

console.log(`borders: ${geometries.length} countries`);
console.log(`codes:   ${entries.length} mapped`);
if (missing.length > 0) {
  console.log(`no ISO code (drawn as no data): ${missing.join(", ")}`);
}
